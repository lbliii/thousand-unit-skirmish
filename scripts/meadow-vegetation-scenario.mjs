import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { meadowPlantPositions, meadowPlantGroups, drylandPlantPositions, drylandPlantGroups, snowPlantPositions, snowPlantGroups, ridgePlantPositions, ridgePlantGroups, lunarPlantPositions, lunarPlantGroups } from '../src/meadow-vegetation.mjs';

const map = JSON.parse(readFileSync(new URL('../maps/bellweather-millrace.json', import.meta.url)));
const original = JSON.stringify(map);
const plants = meadowPlantPositions(map);
assert.ok(plants.length > 20 && plants.length < 180, 'the shipped meadow needs sparse flowers');
assert.equal(JSON.stringify(map), original);
assert.deepEqual(meadowPlantPositions(map), plants);
assert.notDeepEqual(meadowPlantPositions({ ...map, terrainSeed: map.terrainSeed + 1 }), plants);
assert.equal(new Set(plants.map(p => p.cell)).size, plants.length);
const groups = meadowPlantGroups(map);
assert.equal(groups.length, 3, 'shipped meadow needs all three specimens');
assert.deepEqual(groups, meadowPlantGroups(map));
assert.deepEqual(groups.flatMap(g => g.positions).sort((a,b) => a.cell-b.cell), [...plants].sort((a,b) => a.cell-b.cell), 'specimen selection must preserve roots, scale and gaps');
const beds = new Map();
for (const group of groups) for (const p of group.positions) {
  const bed = `${Math.floor(Math.floor(p.cell/map.width)/4)}:${Math.floor((p.cell%map.width)/4)}`;
  assert.ok(!beds.has(bed) || beds.get(bed) === group.name, 'a coarse bed must keep one specimen');
  beds.set(bed, group.name);
}
const desert = JSON.parse(readFileSync(new URL('../maps/sereward-cistern-road.json', import.meta.url)));
const desertOriginal = JSON.stringify(desert), succulents = drylandPlantPositions(desert), dryGroups = drylandPlantGroups(desert);
assert.ok(succulents.length > 10 && succulents.length < 100, 'dryland should have sparse pockets');
assert.equal(dryGroups.length, 2);
assert.deepEqual(dryGroups, drylandPlantGroups(desert));
assert.deepEqual(dryGroups.flatMap(g => g.positions).sort((a,b)=>a.cell-b.cell), [...succulents].sort((a,b)=>a.cell-b.cell));
assert.notDeepEqual(drylandPlantGroups({...desert, terrainSeed:desert.terrainSeed+1}), dryGroups);
assert.equal(new Set(succulents.map(p=>p.cell)).size, succulents.length);
assert.equal(JSON.stringify(desert), desertOriginal);
const winter = JSON.parse(readFileSync(new URL('../maps/pale-meridian-observation-road.json', import.meta.url)));
const winterOriginal = JSON.stringify(winter), snowPlants = snowPlantPositions(winter), snowGroups = snowPlantGroups(winter);
assert.ok(snowPlants.length > 10 && snowPlants.length < 100, 'snow pockets must remain sparse');
assert.equal(snowGroups.length, 2);
assert.deepEqual(snowGroups, snowPlantGroups(winter));
assert.deepEqual(snowGroups.flatMap(g => g.positions).sort((a,b)=>a.cell-b.cell), [...snowPlants].sort((a,b)=>a.cell-b.cell));
assert.notDeepEqual(snowPlantGroups({...winter,terrainSeed:winter.terrainSeed+1}), snowGroups);
assert.equal(new Set(snowPlants.map(p=>p.cell)).size,snowPlants.length);
assert.equal(JSON.stringify(winter),winterOriginal);
for(const terrainBase of ['meadow','sand','ice','lunar-soil','jungle-loam','salt-crust'])assert.deepEqual(snowPlantGroups({...winter,terrainBase}),[]);
assert.deepEqual(snowPlantGroups({...winter,id:'meshy-resource-review'}),[]);
const ridge = JSON.parse(readFileSync(new URL('../maps/veyrholds-slate-saddle.json', import.meta.url)));
const ridgeOriginal = JSON.stringify(ridge), ridgePlants = ridgePlantPositions(ridge), ridgeGroups = ridgePlantGroups(ridge);
assert.ok(ridgePlants.length > 10 && ridgePlants.length < 100, 'ridge slopes need sparse plant pockets');
assert.equal(ridgeGroups.length, 3);
assert.deepEqual(ridgeGroups, ridgePlantGroups(ridge));
assert.deepEqual(ridgeGroups.flatMap(g => g.positions).sort((a,b)=>a.cell-b.cell), [...ridgePlants].sort((a,b)=>a.cell-b.cell));
assert.notDeepEqual(ridgePlantGroups({...ridge,terrainSeed:ridge.terrainSeed+1}), ridgeGroups);
assert.equal(new Set(ridgePlants.map(p=>p.cell)).size,ridgePlants.length);
assert.equal(JSON.stringify(ridge),ridgeOriginal);
for(const terrainBase of ['meadow','sand','snow','ice','lunar-soil','jungle-loam','salt-crust'])assert.deepEqual(ridgePlantGroups({...ridge,terrainBase}),[]);
assert.deepEqual(ridgePlantGroups({...ridge,id:'meshy-resource-review'}),[]);
const lunar = JSON.parse(readFileSync(new URL('../maps/sombral-mere-shore-gardens.json', import.meta.url)));
const lunarOriginal = JSON.stringify(lunar), lunarPlants = lunarPlantPositions(lunar), lunarGroups = lunarPlantGroups(lunar);
assert.ok(lunarPlants.length > 10 && lunarPlants.length < 150, 'lakesides need sparse moon plants');
assert.equal(lunarGroups.length, 2);
assert.deepEqual(lunarGroups,lunarPlantGroups(lunar));
assert.deepEqual(lunarGroups.flatMap(g=>g.positions).sort((a,b)=>a.cell-b.cell),[...lunarPlants].sort((a,b)=>a.cell-b.cell));
assert.notDeepEqual(lunarPlantGroups({...lunar,terrainSeed:lunar.terrainSeed+1}),lunarGroups);
assert.equal(new Set(lunarPlants.map(p=>p.cell)).size,lunarPlants.length);
assert.equal(JSON.stringify(lunar),lunarOriginal);
assert.deepEqual(lunarPlantGroups({...lunar,obstacles:[]}),[],'no lakes means no lake plant beds');
for(const p of lunarPlants) assert.ok(lunar.obstacles.filter(w=>w.material==='water').some(w=>{
  const x0=w.column-lunar.width/2,z0=w.row-lunar.height/2;
  return Math.hypot(Math.max(x0-p.x,0,p.x-x0-w.width),Math.max(z0-p.z,0,p.z-z0-w.height))<=6;
}),'moon plants must stay within the dry lakeside habitat');
for(const terrainBase of ['meadow','sand','snow','scree','jungle-loam','salt-crust'])assert.deepEqual(lunarPlantGroups({...lunar,terrainBase}),[]);
const fixtures = [[map,plants,['meadow','short-grass','long-grass','dry-grass']], [desert,succulents,['sand']], [winter,snowPlants,['snow']], [ridge,ridgePlants,['scree']], [lunar,lunarPlants,['lunar-soil']]];
for (const [map, selected, accepted] of fixtures) for (const p of selected) {
  const c = Math.floor(p.x + map.width / 2), r = Math.floor(p.z + map.height / 2);
  assert.equal(r * map.width + c, p.cell);
  assert.ok(c > 0 && c < map.width - 1 && r > 0 && r < map.height - 1);
  assert.ok(!map.obstacles.some(o => c >= o.column - 1 && c < o.column + o.width + 1 && r >= o.row - 1 && r < o.row + o.height + 1));
  assert.ok(!map.triggers.some(t => t.zone && c >= t.zone.column - 1 && c < t.zone.column + t.zone.width + 1 && r >= t.zone.row - 1 && r < t.zone.row + t.zone.height + 1));
  let material = map.terrainBase;
  for (const t of map.terrainPatches) if (c >= t.column && c < t.column + t.width && r >= t.row && r < t.row + t.height) material = t.material;
  assert.ok(accepted.includes(material));
  assert.ok(map.spawnPoints.every(s => Math.hypot(p.x - s.x, p.z - s.z) >= 8));
  assert.ok(map.resourceNodes.every(s => Math.hypot(p.x - s.x, p.z - s.z) >= 2.5));
}
const bare = { width: 32, height: 32, terrainBase: 'meadow', terrainSeed: 93000 };
assert.ok(meadowPlantPositions(bare).length > 0);
for (const material of ['water','forest','stone']) assert.equal(meadowPlantPositions({ ...bare, obstacles: [{ column: 0, row: 0, width: 32, height: 32, material }] }).length, 0);
assert.equal(meadowPlantPositions({ ...bare, terrainPatches: [{ column: 0, row: 0, width: 32, height: 32, material: 'dirt' }] }).length, 0);
for (const terrainBase of ['sand','snow','ice','lunar-soil','jungle-loam','salt-crust']) assert.equal(meadowPlantPositions({ ...bare, terrainBase }).length, 0);
assert.equal(meadowPlantPositions({ ...bare, id: 'meshy-resource-review' }).length, 0);
assert.deepEqual(meadowPlantGroups({ ...bare, id: 'meshy-resource-review' }), []);
for (const terrainBase of ['meadow','snow','ice','lunar-soil','jungle-loam','salt-crust']) assert.deepEqual(drylandPlantGroups({...desert,terrainBase}), []);
assert.deepEqual(drylandPlantGroups({...desert,id:'meshy-resource-review'}), []);
